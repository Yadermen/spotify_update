# Длительность mp3 в секундах. Сначала ffprobe (идёт в комплекте с ffmpeg,
# который и так нужен yt-dlp), потом mutagen. Раньше длительность умел
# считать только mutagen, и при его отсутствии проверка на 30-секундные
# превью SoundCloud отключалась целиком и молча.
get_duration() {
    local path="$1"
    [ -f "$path" ] || { echo 0; return; }
    local d=""
    if command -v ffprobe >/dev/null 2>&1; then
        d=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$path" 2>/dev/null \
            | cut -d. -f1)
    fi
    if [ -z "$d" ] || [ "$d" = "N/A" ]; then
        d=$(python3 - "$path" <<'DUREOF' 2>/dev/null
import sys
try:
    from mutagen.mp3 import MP3
    print(int(MP3(sys.argv[1]).info.length))
except Exception:
    print(0)
DUREOF
)
    fi
    echo "${d:-0}"
}

