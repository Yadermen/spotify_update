    marker = bad_version_marker(track, result_title)
    if marker:
        return False, f"переработка/другая версия ('{marker}')"

    if " - " in track:
        artists_part, title_part = track.split(" - ", 1)
    else:
        artists_part, title_part = "", track

    artist_words = set()
    for a in [x.strip() for x in artists_part.split(",") if x.strip()]:
        artist_words |= set(significant(a))

    title_words = significant(title_part)
    if not title_words:
        return False, "нет значимых слов в названии"

    result_words_raw = set(words(result_title)) | set(words(result_extra))
    result_words_expanded = expand(result_words_raw)

    matched_title = sum(
        1 for w in title_words
        if w in result_words_expanded or (expand({w}) & result_words_expanded)
    )
    # Короткие названия (<=3 значимых слов) требуют ПОЛНОГО совпадения —
    # раньше хватало половины, из-за чего "Курс на смерть" совпадало по
    # одному слову "смерть" с совершенно другим треком.
    required = len(title_words) if len(title_words) <= 3 else max(1, round(len(title_words) * 0.7))
    title_ok = matched_title >= required

    artist_ok = True
    if artist_words:
        artist_ok = (any(artist_strict(w, result_words_expanded) for w in artist_words)
                     or (len(artist_words) >= 2
                         and all(artist_loose(w, result_words_expanded) for w in artist_words)))

