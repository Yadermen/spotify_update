track_matches_result() {
    local track="$1"
    local result_title="$2"
    local result_extra="${3:-}"
    python3 - "$track" "$result_title" "$result_extra" <<'PYEOF'
import sys, re, difflib

def words(s):
    s = s.lower()
    s = re.sub(r"[^\w\s]", " ", s, flags=re.UNICODE)
    return s.split()

# Служебные слова, которые не должны участвовать в сравнении: они есть почти
# в каждом втором заголовке на YouTube и раньше давали ложные совпадения
# (например, "the" из "The Meto" совпадало с "theatre", "mother" и т.п.).
STOPWORDS = {
    "the","feat","ft","prod","official","music","video","audio","lyric","lyrics",
    "topic","records","record","премьера","клип","песня","трек","текст",
}

def significant(s):
    w = [x for x in words(s) if len(x) >= 3 and x not in STOPWORDS]
    if w:
        return w
    w = [x for x in words(s) if len(x) >= 3]
    return w if w else words(s)

_TABLE_Y = {
    'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'zh','з':'z',
    'и':'i','й':'i','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r',
    'с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'ts','ч':'ch','ш':'sh',
    'щ':'sch','ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya',
}
_TABLE_J = dict(_TABLE_Y)
_TABLE_J.update({'ё':'jo','й':'j','х':'kh','ц':'c','ю':'ju','я':'ja'})

def _translit(word, table):
    return ''.join(table.get(ch, ch) for ch in word)

def expand(word_set):
    expanded = set(word_set)
    for w in word_set:
        for table in (_TABLE_Y, _TABLE_J):
            t = _translit(w, table)
            if t and t != w:
                expanded.add(t)
    return expanded

# Маркеры "это не тот же самый трек": каверы, переводы, karaoke, ускоренные
# версии и т.п. Если маркер есть в НАЙДЕННОМ результате, но его НЕТ в
# запрошенном треке — значит это переработка, а не оригинал, и её брать
# нельзя. Именно отсюда брались "песни на другом языке" (например
# "Korol i Shut - Лесник / Forester (English version by Even Blurry Videos)"
# скачивался вместо оригинала).
VERSION_MARKERS = [
    "cover","кавер","karaoke","караоке","instrumental","инструментал",
    "минус","minus","backing track","semitone","минусовка",
    "english version","russian version","на русском","перевод","translated",
    "acapella","акапелла","nightcore","speed up","sped up","speedup","slowed",
    "reverb","8d","ai cover","mashup","remake","ремейк","live","концерт",
    "acoustic","акустик","tribute","пародия","parody","медляк",
    # ВАЖНО: латинские варианты раньше отсутствовали, был только "ремикс" —
    # из-за этого проходили "HARDSTYLE REMIX", "Phonk Remix By ...",
    # "(DAEPO remix)" и т.п. Если сам трек в плейлисте называется "(Remix)",
    # маркер есть и в запросе, поэтому он НЕ отбрасывается — логика
    # "маркер есть в результате, но нет в запросе" это учитывает.
    "ремикс","remix","rmx","bass boost","bassboost","басс буст","бас буст",
    "edit","версия","version","ускорен","замедлен","hardstyle","phonk",
    # Жанровые "обёртки" чужих пабликов: "DOOMER WAVE | Nautilus Pompilius -
    # Прогулки по воде" — это не оригинал, а чья-то переработка, но никаких
    # слов remix/cover в названии нет. Проверка по границам слов позволяет
    # держать здесь короткие слова вроде mix/wave без ложных срабатываний.
    "doomer","wave","mix","sigma","aesthetic","vaporwave","lofi","lo-fi",
    "funk","drift","memes","meme","mashup","transition","tiktok","тикток",
]

# Однословные маркеры проверяются ПО ГРАНИЦАМ СЛОВ, а не подстрокой:
# иначе "mix" совпадал бы с "remix"/"mixtape"/"Mixail", а "edit" — с
# "editor". Многословные фразы ("english version", "bass boost") ищутся
# как подстрока, там ложных срабатываний практически не бывает.
def bad_version_marker(track, result_title):
    t, r = track.lower(), result_title.lower()
    for m in VERSION_MARKERS:
        if " " in m:
            if m in r and m not in t:
                return m
        else:
            pat = r"(?<![\w])" + re.escape(m) + r"(?![\w])"
            if re.search(pat, r, flags=re.UNICODE) and not re.search(pat, t, flags=re.UNICODE):
                return m
    return None

def artist_strict(needle, hay_expanded):
    # Строгое совпадение: точное равенство (с учётом транслитерации), либо
    # подстрока при СОПОСТАВИМОЙ длине слов, либо высокая (>=0.85) схожесть.
    # Требование сопоставимой длины и минимума 4 символа — ключевое
    # исправление: раньше односимвольное слово из результата ("t" в
    # "Ex-Temple T-one") считалось подстрокой имени артиста ("tolitratim")
    # и любой чужой трек с похожим названием принимался как свой.
    nv = expand({needle})
    if nv & hay_expanded:
        return True
    for a in nv:
        for h in hay_expanded:
            if len(a) < 4 or len(h) < 4:
                continue
            lo, hi = sorted((len(a), len(h)))
            if (a in h or h in a) and lo / hi >= 0.7:
                return True
            if difflib.SequenceMatcher(None, a, h).ratio() >= 0.85:
                return True
    return False

def artist_loose(needle, hay_expanded):
    # Мягкое совпадение (подстрока без ограничения на соотношение длин)
    # разрешено ТОЛЬКО когда у исполнителя несколько значимых слов и ВСЕ они
    # найдены — это случай слитных официальных каналов вида "thekorolishut"
    # для "Korol i Shut". Для однословных имён такое правило слишком слабое
    # ("metan" внутри "metanoia"), поэтому там работает только artist_strict.
    nv = expand({needle})
    return any(len(a) >= 4 and len(h) >= 4 and (a in h or h in a)
               for a in nv for h in hay_expanded)

