    except Exception:
        continue
PYEOF
)
            if [ -n "$archive_match" ] && [ -f "$archive_match" ]; then
                # ПРОВЕРКА ПЕРЕД ВОСКРЕШЕНИЕМ: в архиве может лежать старый
                # огрызок (30-секундное превью SoundCloud), который туда попал
                # до того, как появилась проверка длительности. Возвращать его
                # в актуальный плейлист как полноценный трек нельзя — лучше
                # оставить в архиве и скачать заново резервными эшелонами.
                arch_dur=$(get_duration "$archive_match")
                arch_expected=""
                if [ -f "$DURATIONS_MAP" ]; then
                    arch_expected=$(awk -F'\t' -v t="$track" '$1 == t { print $2; exit }' "$DURATIONS_MAP" 2>/dev/null)
                fi

                arch_ok=true
                if [ "${arch_dur:-0}" -lt 30 ] 2>/dev/null; then
                    arch_ok=false
                    arch_why="файл в архиве длится ${arch_dur}с — похоже на битый огрызок"
                elif [ -n "$arch_expected" ] && [ "$arch_expected" -gt 0 ] \
                     && [ "$((arch_dur * 100))" -lt "$((arch_expected * 60))" ]; then
                    arch_ok=false
                    arch_why="файл в архиве ${arch_dur}с при ожидаемых ~${arch_expected}с — урезанное превью"
                fi

                if [ "$arch_ok" != true ]; then
                    log_main "Воскрешение из архива: \"$track\" найден, но НЕ восстановлен ($arch_why) — оставляем в архиве и качаем заново"
                else
                    dest="$MUSIC_DIR/$(basename "$archive_match")"
                    if mv "$archive_match" "$dest" 2>>"$LOG_ERRORS"; then
                        log_main "Воскрешение из архива: \"$track\" найден в $ARCHIVE_DIR, перенесён обратно в $MUSIC_DIR (докачка не потребовалась)"
                        log_move "ARCHIVE->PLAYLIST" "$track" "воскрешён, ${arch_dur}с"
                        remove_from_failed "$track"
                        RESURRECT_COUNT=$((RESURRECT_COUNT + 1))
                    else
                        log_error "Воскрешение из архива: не удалось перенести \"$archive_match\" -> \"$dest\" для трека \"$track\""
                    fi
                fi
            fi
        done < "$FAILED_FILE"

        if [ "$RESURRECT_COUNT" -gt 0 ]; then
            log_main "Воскрешено из архива: $RESURRECT_COUNT треков"
        else
            log_main "В архиве не найдено совпадений для треков, требующих докачки"
        fi
    else
        log_main "Архив пуст, воскрешать нечего"
    fi
else
    log_main "Проверка архива пропущена (нет mutagen или все треки уже скачаны основным spotdl)"
fi

FAILED_COUNT=$(wc -l < "$FAILED_FILE" | tr -d ' ')


###############################################################################
# Поиск обложки через открытый iTunes Search API
###############################################################################
search_itunes_cover() {
    local track="$1"
    python3 - "$track" <<'PYEOF'
import sys, json, re, urllib.parse, urllib.request

def words(s):
    s = s.lower()
    s = re.sub(r"[^\w\s]", " ", s, flags=re.UNICODE)
    return s.split()

def significant(s):
    w = [x for x in words(s) if len(x) >= 3]
    return w if w else words(s)

track = sys.argv[1]
if " - " in track:
    _, title_part = track.split(" - ", 1)
else:
    title_part = track

title_words = significant(title_part)
if not title_words:
    sys.exit(1)
required_title = max(1, (len(title_words) + 1) // 2)

q = urllib.parse.quote(track)
api_url = f"https://itunes.apple.com/search?term={q}&media=music&entity=song&limit=5"

try:
    req = urllib.request.Request(api_url, headers={"User-Agent": "spotify_update.sh"})
    with urllib.request.urlopen(req, timeout=15) as resp:
        data = json.load(resp)
except Exception:
    sys.exit(1)

for r in data.get("results") or []:
    result_words = set(words(r.get("trackName", ""))) | set(words(r.get("artistName", "")))
    matched_title = sum(1 for w in title_words if w in result_words)
    if matched_title >= required_title:
        art = r.get("artworkUrl100", "")
        if art:
            art = art.replace("100x100bb", "600x600bb")
            print(art)
            sys.exit(0)

sys.exit(1)
PYEOF
}

###############################################################################
# Принудительно проставляет ТОЧНЫЕ TITLE/ARTIST в mp3-файл
###############################################################################
fix_track_tags() {
    local path="$1"
    local track="$2"
    [ "$HAVE_MUTAGEN" = true ] || return 0
    python3 - "$path" "$track" <<'PYEOF' 2>>"$LOG_ERRORS"
import sys
from mutagen.id3 import ID3, ID3NoHeaderError, TIT2, TPE1, TALB, TPE2

path, track = sys.argv[1], sys.argv[2]
if " - " in track:
    artist, title = track.split(" - ", 1)
else:
    artist, title = "", track

try:
    id3 = ID3(path)
except ID3NoHeaderError:
    id3 = ID3()

id3.setall("TIT2", [TIT2(encoding=3, text=title.strip())])
if artist.strip():
    id3.setall("TPE1", [TPE1(encoding=3, text=artist.strip())])

# Альбом = название трека, альбом-исполнитель = исполнитель. Проставляем
# это сразу при скачивании, а не только на финальном этапе 8.1: так каждый
# трек попадает в Navidrome как отдельный "альбом из одной песни" с первой
# же секунды, даже если финальный проход почему-то не отработает.
# TPOS/TRCK (номер диска/трека) убираем — именно они заставляют Navidrome
# слеплять несвязанные треки в общие альбомы "Disc 0"/"Disc 1".
id3.setall("TALB", [TALB(encoding=3, text=title.strip())])
if artist.strip():
    id3.setall("TPE2", [TPE2(encoding=3, text=artist.strip())])
for frame_id in ("TPOS", "TRCK"):
    if frame_id in id3:
        del id3[frame_id]

id3.save(path, v2_version=3)
PYEOF
}

###############################################################################
# Проверяет/вшивает обложку (Spotify -> Deezer -> iTunes)
###############################################################################
ensure_cover_art() {
    local path="$1"
    local track="$2"
    [ "$HAVE_MUTAGEN" = true ] || return 0
    [ -f "$path" ] || return 0

    local has_cover
    has_cover=$(python3 - "$path" <<'PYEOF' 2>>"$LOG_ERRORS"
import sys
from mutagen.id3 import ID3, ID3NoHeaderError
try:
    id3 = ID3(sys.argv[1])
except ID3NoHeaderError:
    print("no")
    sys.exit()
has_apic = any(k.startswith("APIC") for k in id3.keys())
print("yes" if has_apic else "no")
PYEOF
)
    [ "$has_cover" = "yes" ] && return 0

    log_main "ensure_cover_art: обложка отсутствует у \"$track\", ищем..."

    local cover_url="" cover_source=""

    if [ -f "$COVERS_MAP" ]; then
        cover_url=$(awk -F'\t' -v t="$track" '$1 == t { print $2; exit }' "$COVERS_MAP" 2>/dev/null)
        [ -n "$cover_url" ] && cover_source="Spotify"
    fi

    if [ -z "$cover_url" ]; then
        local deezer_result
        deezer_result=$(search_deezer_track "$track")
        if [ -n "$deezer_result" ]; then
            IFS=$'\t' read -r _ _ cover_url <<< "$deezer_result"
            [ -n "$cover_url" ] && cover_source="Deezer"
        fi
    fi

    if [ -z "$cover_url" ]; then
        local itunes_cover
        itunes_cover=$(search_itunes_cover "$track")
        if [ -n "$itunes_cover" ]; then
            cover_url="$itunes_cover"
            cover_source="iTunes"
        fi
    fi

    if [ -z "$cover_url" ]; then
        log_main "ensure_cover_art: подходящая обложка для \"$track\" не найдена ни в Spotify, ни в Deezer, ни в iTunes"
        return 1
    fi

    log_main "ensure_cover_art: используем обложку ($cover_source) для \"$track\""

    if python3 - "$path" "$cover_url" <<'PYEOF' 2>>"$LOG_ERRORS"
import sys, urllib.request
from mutagen.id3 import ID3, ID3NoHeaderError, APIC

path, url = sys.argv[1], sys.argv[2]
try:
    req = urllib.request.Request(url, headers={"User-Agent": "spotify_update.sh"})
    with urllib.request.urlopen(req, timeout=15) as resp:
        image_data = resp.read()
except Exception:
    sys.exit(1)

try:
    id3 = ID3(path)
except ID3NoHeaderError:
    id3 = ID3()

id3.add(APIC(encoding=3, mime="image/jpeg", type=3, desc="Cover", data=image_data))
id3.save(path, v2_version=3)
PYEOF
    then
        log_main "ensure_cover_art: обложка встроена для \"$track\""
        return 0
    else
        log_main "ensure_cover_art: не удалось скачать/встроить обложку для \"$track\""
        return 1
    fi
}

###############################################################################
# Ищет трек через yt-dlp, проверяет соответствие, скачивает, тегирует
###############################################################################
search_validate_download() {
    local search_query="$1"
    local track="$2"
    local label="$3"
    shift 3
    local extra_args=("$@")

    local canonical_track="${CANONICAL_TRACK_OVERRIDE:-$track}"

    log_main "yt-dlp/$label: поисковый запрос \"$search_query\" (искомый трек: \"$track\")"

    # ИСПРАВЛЕНО: раньше запрашивался ровно ОДИН результат (scsearch1/ytsearch1),
    # и если он не подходил — трек считался ненайденным, хотя правильный
    # вариант часто стоял вторым-третьим в выдаче. Это была основная причина
    # "не хватает многих песен". Теперь берём несколько кандидатов и выбираем
    # ПЕРВЫЙ, который проходит проверку названия+исполнителя, а скачиваем уже
    # его прямой URL, а не поисковый запрос.
    local multi_query="$search_query"
    multi_query="${multi_query/#scsearch1:/scsearch${SEARCH_CANDIDATES}:}"
    multi_query="${multi_query/#ytsearch1:/ytsearch${SEARCH_CANDIDATES}:}"

    local candidates
    candidates=$(yt-dlp --print "%(webpage_url)s|||%(title)s|||%(uploader)s" \
        "$multi_query" "${extra_args[@]}" 2>>"$LOG_ERRORS")

    if [ -z "$candidates" ]; then
        log_main "yt-dlp/$label: результат не найден для \"$track\""
        return 1
    fi

    local result_title result_uploader result_url chosen_url="" reject_reason
    local cand_index=0
    while IFS= read -r cand_line; do
        [ -z "$cand_line" ] && continue
        cand_index=$((cand_index + 1))
        result_url="${cand_line%%|||*}"
        local rest="${cand_line#*|||}"
        result_title="${rest%%|||*}"
        result_uploader="${rest#*|||}"

        log_main "yt-dlp/$label: кандидат $cand_index — \"$result_title\" (автор/канал: \"$result_uploader\")"

        reject_reason=$(track_matches_result "$track" "$result_title" "$result_uploader")
        if [ $? -eq 0 ]; then
            chosen_url="$result_url"
            log_main "yt-dlp/$label: кандидат $cand_index принят для \"$track\""
            break
        else
            log_main "yt-dlp/$label: кандидат $cand_index отклонён (${reject_reason:-не соответствует})"
        fi
    done <<< "$candidates"

    if [ -z "$chosen_url" ]; then
        log_main "yt-dlp/$label: ни один из $cand_index кандидатов не подошёл для \"$track\", пропускаем"
        log_error "yt-dlp/$label: подходящих кандидатов нет для \"$track\" (проверено $cand_index)"
        return 1
    fi

    local safe_name
    safe_name=$(python3 -c '
import sys, re
s = sys.argv[1]
s = re.sub(r"[\\/:*?\"<>|]", "_", s)
s = re.sub(r"\s+", " ", s).strip(" .")
print(s[:180] if s else "track")
' "$canonical_track")

    local dl_output dl_exit downloaded_path
    dl_output=$(yt-dlp -x --audio-format mp3 \
        --embed-metadata --embed-thumbnail --convert-thumbnails jpg \
        --print "after_move:filepath" \
        "$chosen_url" \
        --output "$MUSIC_DIR/${safe_name}.%(ext)s" \
        "${extra_args[@]}" \
        2>> "$LOG_ERRORS")
    dl_exit=$?
    [ -n "$dl_output" ] && printf '%s\n' "$dl_output" | tee -a "$LOG_MAIN" >/dev/null

    if [ $dl_exit -eq 0 ]; then
        downloaded_path=$(printf '%s\n' "$dl_output" | tail -n1)
        if [ -f "$downloaded_path" ]; then
            local actual_duration expected_duration
            actual_duration=$(get_duration "$downloaded_path")

            expected_duration=""
            if [ -f "$DURATIONS_MAP" ]; then
                expected_duration=$(awk -F'\t' -v t="$canonical_track" '$1 == t { print $2; exit }' "$DURATIONS_MAP" 2>/dev/null)
            fi

            local MIN_DURATION_SECONDS=40
            local looks_truncated=false
            if [ "$actual_duration" -gt 0 ]; then
                case "$label" in
                    *SoundCloud*)
                        if [ -n "$expected_duration" ] && [ "$expected_duration" -gt 0 ]; then
                            if [ "$((actual_duration * 100))" -lt "$((expected_duration * 60))" ]; then
                                looks_truncated=true
                            fi
                        elif [ "$actual_duration" -lt "$MIN_DURATION_SECONDS" ]; then
                            looks_truncated=true
                        fi
                        ;;
                    *)
                        if [ "$actual_duration" -lt 15 ]; then
                            looks_truncated=true
                        fi
                        ;;
                esac
            fi

            if [ "$looks_truncated" = true ]; then
                log_main "yt-dlp/$label: скачанный файл \"$track\" длится ${actual_duration}с (ожидалось ~${expected_duration:-?}с) — заметно короче ожидаемого (источник: $label; для SoundCloud типичная причина — превью Go+/монетизация, для YouTube — вероятно другой монтаж/edit), отбрасываем и пробуем следующий эшелон"
                log_error "yt-dlp/$label: подозрение на урезанный файл для \"$track\" ($result_title): факт ${actual_duration}с, ожидалось ${expected_duration:-?}с"
                rm -f "$downloaded_path"
                return 1
            fi

            fix_track_tags "$downloaded_path" "$canonical_track"
            ensure_cover_art "$downloaded_path" "$canonical_track"
        fi
        log_main "yt-dlp/$label: успешно скачан \"$track\" (найдено как \"$result_title\")"
        return 0
    else
        log_main "yt-dlp/$label: ошибка скачивания для \"$track\""
        log_error "yt-dlp/$label: ошибка скачивания результата \"$result_title\" для трека \"$track\""
        return 1
    fi
}

