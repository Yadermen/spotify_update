# --- Этап: Вшивание текстов песен (lrxy) ---
#
# ПРИМЕЧАНИЕ: "$MUSIC_DIR"/*.mp3 — обычный shell-glob. Если в MUSIC_DIR по
# какой-то причине нет ни одного mp3 (например spotdl и все резервные
# загрузчики отработали впустую), bash без nullglob передаст lrxy
# буквальную строку "*.mp3" как несуществующее имя файла. shopt -s nullglob
# на время вызова превращает это в пустой список аргументов, тогда просто
# нечего вшивать, а не ошибка обращения к несуществующему файлу.
###############################################################################
log_main "--- Этап: Вшивание текстов песен (lrxy) ---"

if command -v lrxy >/dev/null 2>&1; then
    shopt -s nullglob
    log_main "lrxy: проход 1 (Apple Music)"
    lrxy "$MUSIC_DIR"/*.mp3 --no-overwrite --provider applemusic >> "$LOG_MAIN" 2>> "$LOG_ERRORS"

    log_main "lrxy: проход 2 (LRCLib)"
    lrxy "$MUSIC_DIR"/*.mp3 --no-overwrite --provider lrclib >> "$LOG_MAIN" 2>> "$LOG_ERRORS"
    shopt -u nullglob

    log_main "lrxy: оба прохода завершены"
else
    log_main "lrxy не установлен, пропускаю этап"
fi

###############################################################################
# 8.2 Финальная проверка обложек И длительности
###############################################################################
log_main "--- Этап: Финальная проверка обложек и длительности (обязательное условие) ---"

MISSING_COVERS_FILE="$BASE_DIR/missing_covers.txt"
SHORT_TRACKS_FILE="$BASE_DIR/short_tracks.txt"
: > "$MISSING_COVERS_FILE"
: > "$SHORT_TRACKS_FILE"

if [ "$HAVE_MUTAGEN" = true ]; then
    COVER_CHECKED=0
    COVER_MISSING=0
    SHORT_REMOVED=0

    while IFS= read -r -d '' mp3_path; do
        COVER_CHECKED=$((COVER_CHECKED + 1))

        track_from_tags=$(python3 - "$mp3_path" <<'PYEOF' 2>>"$LOG_ERRORS"
import sys
from mutagen.id3 import ID3, ID3NoHeaderError
try:
    id3 = ID3(sys.argv[1])
except ID3NoHeaderError:
    print("")
    sys.exit()
artist = str(id3.get("TPE1", "") or "")
title = str(id3.get("TIT2", "") or "")
if artist and title:
    print(f"{artist} - {title}")
elif title:
    print(title)
else:
    print("")
PYEOF
)
        [ -z "$track_from_tags" ] && continue

        expected_duration=""
        if [ -f "$DURATIONS_MAP" ]; then
            expected_duration=$(awk -F'\t' -v t="$track_from_tags" '$1 == t { print $2; exit }' "$DURATIONS_MAP" 2>/dev/null)
        fi
        if [ -n "$expected_duration" ] && [ "$expected_duration" -gt 0 ]; then
            actual_duration=$(get_duration "$mp3_path")
            if [ "$actual_duration" -gt 0 ] && [ "$((actual_duration * 100))" -lt "$((expected_duration * 60))" ]; then
                log_main "Финальная проверка: \"$track_from_tags\" длится ${actual_duration}с из ожидаемых ~${expected_duration}с — похоже на урезанный превью-фрагмент, удаляем и пробуем перекачать сразу"
                log_error "Короткий файл удалён: \"$track_from_tags\" ($mp3_path) — факт ${actual_duration}с, ожидалось ${expected_duration}с"
                rm -f "$mp3_path"
                SHORT_REMOVED=$((SHORT_REMOVED + 1))

                redownloaded=false
                if command -v yt-dlp >/dev/null 2>&1; then
                    alias_track=$(lookup_alias "$track_from_tags")
                    if [ -n "$alias_track" ]; then
                        CANONICAL_TRACK_OVERRIDE="$track_from_tags"
                        search_track="$alias_track"
                    else
                        CANONICAL_TRACK_OVERRIDE=""
                        search_track="$track_from_tags"
                    fi
                    if search_validate_download "scsearch1:$search_track" "$search_track" "SoundCloud (повтор после превью)"; then
                        redownloaded=true
                    elif search_validate_download "ytsearch1:$search_track" "$search_track" "YouTube (повтор после превью)" "${YT_EXTRA_ARGS[@]+"${YT_EXTRA_ARGS[@]}"}"; then
                        redownloaded=true
                    fi
                fi
                CANONICAL_TRACK_OVERRIDE=""

                if [ "$redownloaded" = true ]; then
                    log_main "Финальная проверка: \"$track_from_tags\" успешно перекачан полностью"
                else
                    log_main "Финальная проверка: перекачать \"$track_from_tags\" полностью не удалось ни через один резервный источник, трек удалён из библиотеки без замены"
                    echo "$track_from_tags" >> "$SHORT_TRACKS_FILE"
                fi
                continue
            fi
        fi

        if ! ensure_cover_art "$mp3_path" "$track_from_tags"; then
            echo "$track_from_tags" >> "$MISSING_COVERS_FILE"
            COVER_MISSING=$((COVER_MISSING + 1))
        fi
    done < <(find "$MUSIC_DIR" -type f -name "*.mp3" -print0)

    log_main "Финальная проверка обложек: проверено $COVER_CHECKED файлов, без обложки осталось $COVER_MISSING"
    log_main "Финальная проверка длительности: удалено урезанных превью-файлов $SHORT_REMOVED (список: $SHORT_TRACKS_FILE)"
    if [ "$COVER_MISSING" -gt 0 ]; then
        log_main "Список треков без обложки (ни Spotify, ни Deezer, ни iTunes не дали результата): $MISSING_COVERS_FILE"
    fi
else
    log_main "Пропуск финальной проверки обложек (модуль mutagen недоступен)"
fi

###############################################################################
# 8.3 Синхронизация с плейлистом: треки, ушедшие из плейлиста Spotify,
# переносятся в $ARCHIVE_DIR — ВТОРУЮ, отдельную от актуальной, но всё ещё
# видимую в Navidrome папку/плейлист. Это не мусорка: файлы там продолжают
# существовать, слушаться и участвовать в 5.15 ("воскрешение"), если трек
# однажды вернётся в актуальный плейлист.
#
# ИДЕЯ: вместо того чтобы полагаться на архив spotdl (который, как показал
# баг с "призраками", может расходиться с реальностью), на каждом запуске
# напрямую сравниваем СВЕЖИЙ список треков плейлиста (playlist_meta.spotdl,
# только что перезаписанный текущим запуском spotdl) с тем, что реально лежит
# в $MUSIC_DIR — по ID3-тегам (TPE1/TIT2), а не по имени файла, потому что
# spotdl и резервные загрузчики могут называть файлы чуть по-разному.
#
# ДВЕ ЗАЩИТЫ от случайного массового переноса:
#   1) Если playlist_meta.spotdl в ЭТОМ запуске содержит подозрительно мало
#      треков (меньше 5, или меньше половины текущего размера библиотеки) —
#      это явный признак того, что получение метаданных плейлиста прошло не
#      полностью (сбой сети/лимиты Spotify API), а не что плейлист правда
#      так сильно уменьшился. В этом случае синхронизация НЕ выполняется
#      вообще, только предупреждение в лог.
#   2) Если "лишних" больше 15% от размера библиотеки (но не меньше 5
#      треков) — тоже ничего не трогаем автоматически, только сохраняем
#      список кандидатов в файл для ручной проверки.
###############################################################################
log_main "--- Этап: Синхронизация библиотеки с плейлистом ---"

SYNC_CANDIDATES_FILE="$BASE_DIR/sync_review_needed.txt"
SYNC_ARCHIVED_FILE="$BASE_DIR/sync_archived_log.txt"

if [ "$HAVE_MUTAGEN" = true ] && [ -f "$PLAYLIST_META" ]; then
    mapfile -d '' -t ALL_MP3 < <(find "$MUSIC_DIR" -type f -name "*.mp3" -print0)

    SYNC_RESULT=$(python3 - "$PLAYLIST_META" "$ARCHIVE_DIR" "$SYNC_CANDIDATES_FILE" "$SYNC_ARCHIVED_FILE" "$ARCHIVE_MOVE_CAP_PERCENT" "${ALL_MP3[@]}" 2>>"$LOG_ERRORS" <<'PYEOF'
import sys, json, os, re, shutil, datetime
from mutagen.id3 import ID3, ID3NoHeaderError

meta_path, archive_dir, candidates_path, archived_log_path = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
cap_percent = float(sys.argv[5])
mp3_paths = sys.argv[6:]

def norm(s):
    s = s.lower()
    s = re.sub(r"[^\w\s]", " ", s, flags=re.UNICODE)
    return re.sub(r"\s+", " ", s).strip()

try:
    with open(meta_path, encoding="utf-8") as f:
        songs = json.load(f)
except Exception:
    print("ABORT\t0\t0\t0\t0")
    sys.exit()

playlist_set = set()
for s in songs:
    name = s.get("name") or ""
    artists = s.get("artists") or ([s["artist"]] if s.get("artist") else [])
    if name:
        canonical = f"{', '.join(artists)} - {name}" if artists else name
        playlist_set.add(norm(canonical))

disk_total = len(mp3_paths)

# Защита 1: подозрительно неполные метаданные плейлиста в этом запуске.
if len(songs) < 5 or (disk_total > 0 and len(songs) < disk_total * 0.5):
    print(f"ABORT\t{len(songs)}\t{disk_total}\t0\t0")
    sys.exit()

extras = []
for path in mp3_paths:
    try:
        try:
            id3 = ID3(path)
        except ID3NoHeaderError:
            continue
        artist = str(id3.get("TPE1", "") or "").strip()
        title = str(id3.get("TIT2", "") or "").strip()
        if not title:
            continue
        canonical = f"{artist} - {title}" if artist else title
        if norm(canonical) not in playlist_set:
            extras.append((path, canonical))
    except Exception:
        continue

# Защита 2: слишком много "лишних" за один раз — не действуем автоматически.
cap = max(5, round(disk_total * cap_percent / 100)) if disk_total > 0 else 5
if len(extras) > cap:
    with open(candidates_path, "w", encoding="utf-8") as cf:
        for _, canonical in extras:
            cf.write(canonical + "\n")
    print(f"CAPPED\t{len(songs)}\t{disk_total}\t{len(extras)}\t{cap}")
    sys.exit()

moved = 0
stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
human_stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
moves_log_path = os.path.join(os.path.dirname(archive_dir), "moves.log")
moves_log = open(moves_log_path, "a", encoding="utf-8")
with open(archived_log_path, "a", encoding="utf-8") as rf:
    for path, canonical in extras:
        try:
            base = os.path.basename(path)
            dest = os.path.join(archive_dir, base)
            if os.path.exists(dest):
                # Коллизия имён (маловероятно) — добавляем метку времени.
                dest = os.path.join(archive_dir, f"{stamp}__{base}")
            shutil.move(path, dest)
            moved += 1
            rf.write(f"{stamp}\t{canonical}\t{dest}\n")
            moves_log.write(f"{human_stamp} | PLAYLIST->ARCHIVE | {canonical}\n")
        except Exception as e:
            rf.write(f"{stamp}\tMOVE_ERROR\t{canonical}\t{e}\n")

moves_log.close()
print(f"OK\t{len(songs)}\t{disk_total}\t{len(extras)}\t{moved}")
PYEOF
)
    SYNC_STATUS="${SYNC_RESULT%%$'\t'*}"
    SYNC_REST="${SYNC_RESULT#*$'\t'}"
    SYNC_META_COUNT="${SYNC_REST%%$'\t'*}"
    SYNC_REST="${SYNC_REST#*$'\t'}"
    SYNC_DISK_COUNT="${SYNC_REST%%$'\t'*}"
    SYNC_REST="${SYNC_REST#*$'\t'}"
    SYNC_EXTRA_COUNT="${SYNC_REST%%$'\t'*}"
    SYNC_LAST="${SYNC_REST#*$'\t'}"

    case "$SYNC_STATUS" in
        ABORT)
            log_main "Синхронизация с плейлистом пропущена: метаданные плейлиста в этом запуске выглядят неполными ($SYNC_META_COUNT треков против $SYNC_DISK_COUNT в библиотеке) — вероятен сбой при получении данных Spotify, а не реальное уменьшение плейлиста. Ничего не тронуто."
            ;;
        CAPPED)
            log_main "Синхронизация с плейлистом: найдено $SYNC_EXTRA_COUNT треков на диске, которых нет в текущем плейлисте — это больше защитного порога ($SYNC_LAST), автоматически ничего не перенесено. Список кандидатов на ручную проверку: $SYNC_CANDIDATES_FILE"
            ;;
        OK)
            if [ "${SYNC_EXTRA_COUNT:-0}" -gt 0 ] 2>/dev/null; then
                log_main "Синхронизация с плейлистом: $SYNC_LAST из $SYNC_EXTRA_COUNT треков, ушедших из плейлиста, перенесены в архив $ARCHIVE_DIR (журнал: $SYNC_ARCHIVED_FILE)"
            else
                log_main "Синхронизация с плейлистом: лишних треков не найдено, библиотека в актуальном состоянии"
            fi
            ;;
        *)
            log_main "Синхронизация с плейлистом: неожиданный результат ($SYNC_RESULT), пропускаем без изменений"
            ;;
    esac
else
    log_main "Синхронизация с плейлистом пропущена (нет mutagen или $PLAYLIST_META)"
fi

###############################################################################
# 8.4 Пересборка Playlist.m3u — ТЕПЕРЬ ПОСЛЕ 8.1/8.2/8.3, а не до них
#
# ИСПРАВЛЕНО: раньше `find . -name "*.mp3" > Playlist.m3u` выполнялся ДО
# шагов 8.1 (тегирование) и 8.2 (проверка обложек/длительности), а шаг 8.2
# может УДАЛЯТЬ файлы (урезанные превью) и ДОБАВЛЯТЬ новые (успешная
# перекачка на замену). При старом порядке Playlist.m3u мог: (а) содержать
# путь к файлу, который 8.2 только что удалил и не смог заменить — то есть
# ссылаться в никуда; (б) НЕ содержать файл, который 8.2 успешно перекачал
# на замену только что удалённого — трек фактически есть в библиотеке, но
# плейлист о нём не знает до следующего запуска. Пересборка перенесена в
# самый конец, чтобы Playlist.m3u всегда отражал финальное, а не
# промежуточное состояние каталога.
###############################################################################
# Битые файлы (не читаются как mp3) уезжают в Corrupted/, чтобы не висеть
# в библиотеке молча и не попадать в .m3u.
if [ "$HAVE_MUTAGEN" = true ]; then
    CORRUPT_MOVED=0
    while IFS= read -r -d '' bad_path; do
        if ! python3 - "$bad_path" <<'CORREOF' 2>>"$LOG_ERRORS"
import sys
from mutagen.mp3 import MP3
try:
    info = MP3(sys.argv[1]).info
    sys.exit(0 if info.length > 0 else 1)
except Exception:
    sys.exit(1)
CORREOF
        then
            if mv "$bad_path" "$CORRUPTED_DIR/" 2>>"$LOG_ERRORS"; then
                log_main "Битый файл перенесён в $CORRUPTED_DIR: $(basename "$bad_path")"
                log_move "->CORRUPTED" "$(basename "$bad_path")" "файл не читается как mp3"
                CORRUPT_MOVED=$((CORRUPT_MOVED + 1))
            fi
        fi
    done < <(find "$MUSIC_DIR" -type f -name "*.mp3" -print0)
    [ "$CORRUPT_MOVED" -gt 0 ] && log_main "Битых файлов перенесено в карантин: $CORRUPT_MOVED"
fi

# ПРИМЕЧАНИЕ про "мёртвые" записи в .m3u: список строится через `find` по
# фактически существующим файлам прямо сейчас, уже ПОСЛЕ всех перемещений
# (8.1-8.3) и после отсева битых выше, поэтому ссылок в никуда в нём
# появиться не может по построению — отдельная чистка не нужна.
rm -f "Playlist.m3u"
find . -name "*.mp3" > "Playlist.m3u"
log_main "Playlist.m3u пересоздан ($(wc -l < Playlist.m3u | tr -d ' ') треков)"

# Тот же принцип для второй, архивной библиотеки — пересобираем её плейлист
# тоже в самом конце, после того как 8.3 закончил переносить в неё файлы.
if cd "$ARCHIVE_DIR" 2>/dev/null; then
    rm -f "Archive.m3u"
    find . -name "*.mp3" > "Archive.m3u"
    log_main "Archive.m3u пересоздан ($(wc -l < Archive.m3u | tr -d ' ') треков)"
    cd "$MUSIC_DIR" || fail_critical "Не удалось вернуться в каталог $MUSIC_DIR"
else
    log_main "ПРЕДУПРЕЖДЕНИЕ: не удалось перейти в $ARCHIVE_DIR для пересборки Archive.m3u"
fi

if docker restart navidrome >> "$LOG_MAIN" 2>> "$LOG_ERRORS"; then
    log_main "Navidrome успешно перезапущен"
else
    log_main "Не удалось перезапустить Navidrome (контейнер navidrome)"
    log_error "docker restart navidrome завершился с ошибкой"
fi

###############################################################################
# 7. Подсчёт итоговой статистики
###############################################################################
AFTER=$(find "$MUSIC_DIR" -type f -iname "*.mp3" 2>/dev/null | wc -l | tr -d ' ')
DIFF=$((AFTER - BEFORE))

log_main "$(ts) - СКАЧАНО ЗА ЭТОТ ЗАПУСК: $DIFF треков"
log_main "$(ts) - ВСЕГО ТРЕКОВ: $AFTER"

REMAINING=$(wc -l < "$FAILED_FILE" | tr -d ' ')
log_main "Треков, оставшихся нескачанными после всех эшелонов: $REMAINING"
if [ "$REMAINING" -gt 0 ]; then
    log_main "Список нескачанных треков сохранён в $FAILED_FILE"
fi

log_main "Скрипт spotify_update.sh завершён успешно"
log_main "===================================================================="

exit 0
